"""Write saved CEA comparisons for the GUI's reference and self-check pages.

These facts are not solver outputs (the GUI cannot rerun CEA or the test
suite), so they are copied from the verified demo data block, which
tools/demo_data.py builds from results/validation/* manifests and the tested
Release build. Rerun after regenerating the demo page.

    python tools/gui_archive.py [--source deliverables/demo/index.html]
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = re.compile(r'<script id="rp-data" type="application/json">(.*?)</script>', re.S)
OUT = ROOT / "src/gui/web/archive.js"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=ROOT / "deliverables/demo/index.html")
    args = parser.parse_args()
    found = DATA.search(args.source.read_text(encoding="utf-8"))
    if not found:
        raise SystemExit(f"No embedded data block in {args.source}")
    data = json.loads(found.group(1))
    keep = {"validation": data["validation"],
            "provenance": {k: data["provenance"][k] for k in ("binary_sha256", "git_head", "generated_at", "c_runs")}}
    text = json.dumps(keep, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text('"use strict";\n/* Generated by tools/gui_archive.py from the verified demo data; archived facts, not live solves. */\n'
                   f"const ARCHIVE = {text};\n", encoding="utf-8")
    print(f"PASS {OUT.relative_to(ROOT).as_posix()} ({OUT.stat().st_size / 1024:.0f} KiB)")


if __name__ == "__main__":
    main()
